// ---------------------------------------------------------
// User prompt：把规则引擎结果序列化进去
// ---------------------------------------------------------
export function buildUserPrompt(
  reportType: ReportType,
  tier: ReportTier,
  ruleResult: unknown
): string {
  const tierLabel = tier === "deep" ? "深度版" : "基础版";
  const conversationalTypes: ReportType[] = [
    "bazi_basic", "marriage_basic", "marriage_deep",
    "home_fengshui_basic", "home_fengshui_deep",
    "date_selection_basic", "date_selection"
  ];
  const conversationalReminder = conversationalTypes.includes(reportType)
    ? "核心结论、依据、提醒、建议与免责声明只需融入聊天式章节，不要直接使用“分析 / 判断 / 风险点 / 依据”作为标题。"
    : "";
  return [
    `请根据以下结构化输入，生成「${tierLabel}」报告。`,
    "",
    "【结构化输入开始】",
    "```json",
    JSON.stringify(ruleResult, null, 2),
    "```",
    "【结构化输入结束】",
    "",
    "请严格按章节标题输出 markdown（不要在标题外加解释）。",
    "确保报告中包含【核心结论 / 依据 / 风险点 / 可执行建议 / 免责声明】这 5 个语义模块。",
    conversationalReminder
  ].filter(Boolean).join("\n");
}
