export function buildSystemPrompt(reportType: ReportType, _tier: ReportTier): string {
  return [SHARED_SYSTEM_PROMPT, PER_REPORT_SYSTEM[reportType].trim()].join("\n\n");
}

// ---------------------------------------------------------
// User prompt：把规则引擎结果序列化进去
// ---------------------------------------------------------
export function buildUserPrompt(
  reportType: ReportType,
  tier: ReportTier,
  ruleResult: unknown
): string {
  const tierLabel = tier === "deep" ? "深度版" : "基础版";
  return [
    `请根据以下结构化输入，生成「${tierLabel}」报告。`,
    "",
    "【结构化输入开始】",
    "```json",
    JSON.stringify(ruleResult, null, 2),
    "```",
    "【结构化输入结束】",
    "",
    "请严格按章节标题输出 markdown（不要在标题外加解释）。",
    "确保报告中包含【核心结论 / 依据 / 风险点 / 可执行建议 / 免责声明】这 5 个语义模块。"
  ].join("\n");
}
