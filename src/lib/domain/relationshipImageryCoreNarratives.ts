function buildApprovedCoreDraftsByKey(): Map<
  BaziNarrativeKey,
  ApprovedCoreDraft
> {
  const draftsByKey = new Map<BaziNarrativeKey, ApprovedCoreDraft>();
  for (const draft of APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS) {
    if (draftsByKey.has(draft[0])) {
      throw new Error(`Duplicate relationship imagery core key: ${draft[0]}`);
    }
    draftsByKey.set(draft[0], draft);
  }
  return draftsByKey;
}

const APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS_BY_KEY =
  buildApprovedCoreDraftsByKey();

function approvedCoreEntry(
  draft: ApprovedCoreDraft
): RelationshipImageryCoreEntry {
  const [selectionKey, title, narrative] = draft;
  const source = BAZI_DIRECT_NARRATIVE_CATALOG[selectionKey];
  return {
    id: `relationship-imagery-core:${selectionKey}:v1`,
    selectionKey,
    title,
    narrative,
    requiredFacts: {
      dayStem: source.dayStem,
      dayElement: source.requiredFacts.dayElement,
      dayYinYang: source.requiredFacts.dayYinYang,
      monthBranch: source.monthBranch,
      monthMainStem: source.requiredFacts.monthMainStem,
      monthMainTenGod: source.requiredFacts.monthMainTenGod
    },
    factDependencies: source.factDependencies,
    reviewStatus: "human_reviewed_approved",
    contentVersion: RELATIONSHIP_IMAGERY_CORE_CONTENT_VERSION
  };
}

function buildApprovedCoreCatalog(): Record<
  BaziNarrativeKey,
  RelationshipImageryCoreEntry
> {
  const baziKeys = Object.keys(BAZI_DIRECT_NARRATIVE_CATALOG) as BaziNarrativeKey[];
  if (
    APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS_BY_KEY.size !== baziKeys.length
    || baziKeys.some(
      key => !APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS_BY_KEY.has(key)
    )
  ) {
    throw new Error("Relationship imagery core catalog must cover the complete Bazi imagery catalog");
  }
  return Object.fromEntries(
    baziKeys.map(key => [
      key,
      approvedCoreEntry(
        APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS_BY_KEY.get(key)!
      )
    ])
  ) as Record<BaziNarrativeKey, RelationshipImageryCoreEntry>;
}

export const RELATIONSHIP_IMAGERY_CORE_CATALOG = buildApprovedCoreCatalog();

export interface RelationshipParticipantImageryCore {
  id: "personA" | "personB";
  label: "你" | "对方";
  selectionKey: BaziNarrativeKey;
  entry: RelationshipImageryCoreEntry;
  narrative: string;
}

export type RelationshipImageryCoreSelection =
  | {
      status: "available";
      participants: [
        RelationshipParticipantImageryCore,
        RelationshipParticipantImageryCore
      ];
    }
  | { status: "not_available"; reason: "input_unavailable" };

function matchesApprovedBaziSource(
  participant: Extract<RelationshipImageryInput, { status: "available" }>["participants"][number]
): boolean {
  const source = BAZI_DIRECT_NARRATIVE_CATALOG[participant.selectionKey];
  if (
    !source
    || participant.entry !== source
    || source.reviewStatus !== "human_reviewed_approved"
  ) {
    return false;
  }
  const expectedValues: Record<
    (typeof BAZI_DIRECT_NARRATIVE_FACT_IDS)[number],
    unknown
  > = {
    "dayMaster.stem": source.dayStem,
    "dayMaster.element": source.requiredFacts.dayElement,
    "dayMaster.yinYang": source.requiredFacts.dayYinYang,
    "monthCommand.branch": source.monthBranch,
    "monthCommand.mainStem": source.requiredFacts.monthMainStem,
    "monthCommand.mainTenGod": source.requiredFacts.monthMainTenGod
  };
  return BAZI_DIRECT_NARRATIVE_FACT_IDS.every(factId => {
    const fact = participant.dependencyFacts[factId];
    return (
      fact.certainty === "confirmed"
      && fact.value === expectedValues[factId]
      && fact.sourcePosition.length > 0
      && fact.sourceRuleId.length > 0
      && fact.ruleVersion.length > 0
    );
  });
}

function matchesApprovedCoreBinding(
  entry: RelationshipImageryCoreEntry | undefined,
  selectionKey: BaziNarrativeKey
): entry is RelationshipImageryCoreEntry {
  const source = BAZI_DIRECT_NARRATIVE_CATALOG[selectionKey];
  const approvedDraft =
    APPROVED_RELATIONSHIP_IMAGERY_CORE_DRAFTS_BY_KEY.get(selectionKey);
  return Boolean(
    entry
    && source
    && approvedDraft
    && entry.selectionKey === selectionKey
    && entry.id === `relationship-imagery-core:${selectionKey}:v1`
    && entry.title === approvedDraft[1]
    && entry.narrative === approvedDraft[2]
    && entry.reviewStatus === "human_reviewed_approved"
    && entry.contentVersion === RELATIONSHIP_IMAGERY_CORE_CONTENT_VERSION
    && entry.requiredFacts.dayStem === source.dayStem
    && entry.requiredFacts.dayElement === source.requiredFacts.dayElement
    && entry.requiredFacts.dayYinYang === source.requiredFacts.dayYinYang
    && entry.requiredFacts.monthBranch === source.monthBranch
    && entry.requiredFacts.monthMainStem === source.requiredFacts.monthMainStem
    && entry.requiredFacts.monthMainTenGod === source.requiredFacts.monthMainTenGod
    && entry.factDependencies === source.factDependencies
  );
}

export function relationshipImageryCoreForOther(
  approvedNarrative: string
): string {
  return approvedNarrative.replaceAll("你", "对方");
}

export function selectRelationshipImageryCore(
  input: RelationshipImageryInput
): RelationshipImageryCoreSelection {
  if (
    input.status !== "available"
    || input.participants[0].id !== "personA"
    || input.participants[0].label !== "你"
    || input.participants[1].id !== "personB"
    || input.participants[1].label !== "对方"
    || !input.participants.every(matchesApprovedBaziSource)
  ) {
    return { status: "not_available", reason: "input_unavailable" };
  }
  const personAEntry =
    RELATIONSHIP_IMAGERY_CORE_CATALOG[input.participants[0].selectionKey];
  const personBEntry =
    RELATIONSHIP_IMAGERY_CORE_CATALOG[input.participants[1].selectionKey];
  if (
    !matchesApprovedCoreBinding(
      personAEntry,
      input.participants[0].selectionKey
    )
    || !matchesApprovedCoreBinding(
      personBEntry,
      input.participants[1].selectionKey
    )
  ) {
    return { status: "not_available", reason: "input_unavailable" };
  }
  return {
    status: "available",
    participants: [
      {
        id: "personA",
        label: "你",
        selectionKey: personAEntry.selectionKey,
        entry: personAEntry,
        narrative: personAEntry.narrative
      },
      {
        id: "personB",
        label: "对方",
        selectionKey: personBEntry.selectionKey,
        entry: personBEntry,
        narrative: relationshipImageryCoreForOther(personBEntry.narrative)
      }
    ]
  };
}
